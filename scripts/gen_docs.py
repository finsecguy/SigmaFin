"""Generate docs/rule-catalog.md, docs/attack-coverage.md and the README rule table.

Run with --check in CI to fail when the committed files are out of date.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml
from sigma.data.mitre_attack import mitre_attack_techniques

import sigmafin_lib as lib

DOCS = lib.ROOT / "docs"
README = lib.ROOT / "README.md"
OVERLAP = DOCS / "sigmahq_overlap.yml"
START, END = "<!-- RULES:START -->", "<!-- RULES:END -->"

THEMES = {
    "bec_payment_fraud": "1. BEC and payment fraud",
    "erp_vendor_payment": "2. Vendor and payment manipulation (ERP)",
    "erp_privileged_access": "3. Privileged ERP and finance app abuse",
    "exfiltration_insider": "4. Finance data exfiltration and insider risk",
    "account_takeover": "5. Account takeover of finance staff",
    "ai_leakage": "6. Data leakage to AI services",
}


def techniques(data: dict) -> list[str]:
    out = []
    for tag in data.get("tags") or []:
        m = re.match(r"^attack\.(t\d{4}(?:\.\d{3})?)$", tag)
        if m:
            out.append(m.group(1).upper())
    return out


def logsource(doc: lib.RuleDoc, index) -> str:
    if doc.is_correlation:
        srcs = []
        for ref in doc.references:
            s = logsource(index[ref], index)
            if s not in srcs:
                srcs.append(s)
        return " + ".join(srcs)
    ls = doc.data["logsource"]
    return "/".join(str(ls[k]) for k in ("product", "category", "service") if ls.get(k))


def kind(doc: lib.RuleDoc, support: set[str]) -> str:
    if doc.is_correlation:
        return "correlation: " + doc.data["correlation"]["type"]
    return "support rule" if doc.name in support else "single event"


def technique_cell(doc: lib.RuleDoc) -> str:
    ts = techniques(doc.data)
    if not ts:
        return "none (fraud or support rule)"
    return ", ".join(f"{t} {mitre_attack_techniques.get(t, '?')}" for t in ts)


def build_readme_table(docs, index, support) -> str:
    lines = ["| Rule | Theme | ATT&CK technique | Log source | Level |", "|---|---|---|---|---|"]
    for doc in sorted(docs, key=lambda d: (list(THEMES).index(d.theme) if d.theme in THEMES else 99, d.name)):
        lines.append(
            f"| {doc.data['title']} (`{doc.name}`) | {THEMES.get(doc.theme, doc.theme)} | {technique_cell(doc)} "
            f"| {logsource(doc, index)} | {doc.data['level']} |"
        )
    return "\n".join(lines)


def build_catalog(docs, index, support, overlap) -> str:
    out = ["# Rule catalog", "", "Generated by `scripts/gen_docs.py`. Do not edit by hand.", "",
           f"Rules: {len(docs)} (including support rules). Overlap data: `docs/sigmahq_overlap.yml`.", "",
           "| Rule | Kind | Status | Level | SigmaHQ overlap | Decision |", "|---|---|---|---|---|---|"]
    for doc in sorted(docs, key=lambda d: (d.theme, d.name)):
        entry = overlap.get("rules", {}).get(doc.name, {})
        ids = ", ".join(o["id"][:8] for o in entry.get("overlap", [])) or "none found"
        out.append(f"| `{doc.name}` | {kind(doc, support)} | {doc.data['status']} | {doc.data['level']} | {ids} | {entry.get('decision', 'NOT RECORDED')} |")
    out += ["", "## SigmaHQ overlap detail", ""]
    for doc in sorted(docs, key=lambda d: (d.theme, d.name)):
        entry = overlap.get("rules", {}).get(doc.name)
        out.append(f"### `{doc.name}`")
        if not entry:
            out += ["", "No overlap check recorded.", ""]
            continue
        out += ["", f"- Search terms: {', '.join(entry['search_terms'])}", f"- Decision: {entry['decision']}",
                f"- What this repo adds: {entry['scoping_added']}"]
        for o in entry.get("overlap", []):
            out.append(f"- Related SigmaHQ rule `{o['id']}` (`{o['path']}`): {o['note']}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def build_coverage(docs, index, support) -> str:
    by_tech: dict[str, list[str]] = {}
    no_tech = []
    for doc in docs:
        ts = techniques(doc.data)
        for t in ts:
            by_tech.setdefault(t, []).append(doc.name)
        if not ts:
            no_tech.append(doc.name)
    out = ["# ATT&CK coverage", "", "Generated by `scripts/gen_docs.py`. Do not edit by hand.", "",
           "Coverage here means a rule is tagged with the technique. It does not claim the rule detects every "
           "procedure of that technique. Names come from the ATT&CK data bundled with the installed pySigma.", "",
           "| Technique | Name | Rules |", "|---|---|---|"]
    for t in sorted(by_tech):
        out.append(f"| {t} | {mitre_attack_techniques.get(t, '?')} | {', '.join(f'`{n}`' for n in sorted(by_tech[t]))} |")
    out += ["", "## Rules without a technique tag", "", "Allowed only when listed in `scripts/policy.yml` with a reason.", ""]
    for n in sorted(no_tech):
        out.append(f"- `{n}`")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    docs = lib.load_rule_docs()
    index = lib.index_docs(docs)
    support = set(lib.load_policy().get("support_rules", []))
    overlap = yaml.safe_load(OVERLAP.read_text(encoding="utf-8"))

    readme = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(readme):
        print(f"README.md is missing the {START} / {END} markers")
        return 1
    new_readme = pattern.sub(lambda _: f"{START}\n{build_readme_table(docs, index, support)}\n{END}", readme)

    outputs = {
        DOCS / "rule-catalog.md": build_catalog(docs, index, support, overlap),
        DOCS / "attack-coverage.md": build_coverage(docs, index, support),
        README: new_readme,
    }
    stale = []
    for path, text in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path.name)
        if not args.check:
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("Out of date, run `python scripts/gen_docs.py`: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
